"""Funciones aritméticas básicas para usar como módulo simple."""

def suma(a, b):
    """Devuelve la suma de *a* y *b*."""
    return a + b


def resta(a, b):
    """Devuelve la diferencia entre *a* y *b*."""
    return a - b


def multiplicacion(a, b):
    """Devuelve el producto de *a* y *b*."""
    return a * b
